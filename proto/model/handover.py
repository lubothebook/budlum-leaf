#!/usr/bin/env python3
"""Handover timing of the shadow validator (gate DST-12).

Three shadow states: WARM (heartbeat only), HOT (dual send: both validators
send slices, U6 keeps the first good one per slice), and SWITCH.
Computes, for a set of shadow round trips:
  * planned handover from WARM: the lead in frames for HandoverCommand;
  * unplanned primary loss from WARM: the frames U1 must cover by reprojection;
  * unplanned primary loss from HOT: frames lost (zero by construction);
  * the cost of HOT: the extra downlink.
Run:  python3 model/handover.py   [HYPOTHESIS] inputs, see the constants.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bitrate  # noqa: E402

PERIOD_MS = 1000 / 240
ENCODE_FIRST_SLICE_MS = 1.5   # FINAL/21 21.5.7
DECODE_FIRST_SLICE_MS = 1.5
DETECT_MS = 2 * PERIOD_MS     # two frame periods with no slice from the primary [HYPOTHESIS]
REPROJECT_MAX_MS = 40         # FINAL/08 8.6.2


def planned_lead_frames(rtt_ms):
    return math.ceil((rtt_ms + ENCODE_FIRST_SLICE_MS + DECODE_FIRST_SLICE_MS) / PERIOD_MS) + 1


def unplanned_gap_frames(rtt_ms):
    return math.ceil((DETECT_MS + rtt_ms + ENCODE_FIRST_SLICE_MS + DECODE_FIRST_SLICE_MS) / PERIOD_MS)


def main():
    rows, _, _ = bitrate.downlink_table()
    hot = next(r for r in rows if r["content"].startswith("game, full") and r["codec"] == "AV1")
    lines = ["| shadow RTT ms | planned lead, frames | unplanned from WARM: frames covered by U1 | "
             "covered time ms | inside the 40 ms reprojection limit | unplanned from HOT: frames lost |",
             "|---|---|---|---|---|---|"]
    for rtt in (0.5, 1, 3, 6, 12, 25):
        gap = unplanned_gap_frames(rtt)
        lines.append(f"| {rtt} | {planned_lead_frames(rtt)} | {gap} | {gap*PERIOD_MS:.1f} | "
                     f"{'yes' if gap*PERIOD_MS <= REPROJECT_MAX_MS else 'no'} | 0 |")
    lines.append(f"\nHOT state cost: one more slice stream, {hot['stream_total']/1e6:.1f} Mbit/s "
                 "for game AV1. The Leaf enters HOT only when the primary RTT or loss trend "
                 "crosses the warning line.\n")
    text = "# Handover timing (generated by model/handover.py)\n\n" + "\n".join(lines) + "\n"
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "out", "handover.md")
    open(out, "w").write(text)
    print(text)


if __name__ == "__main__":
    main()
